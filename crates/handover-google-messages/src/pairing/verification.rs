//! Revision-1 verification alphabet observed in Google's public pairing UI.
//! Functional symbol-to-index data only; no Google application implementation.

use std::fmt;

/// Intended for the pairing display. Debug redacts it; no serialization is provided.
pub struct VerificationEmoji(&'static str);

impl fmt::Debug for VerificationEmoji {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str("VerificationEmoji { redacted }")
    }
}

impl VerificationEmoji {
    pub fn as_str(&self) -> &'static str {
        self.0
    }
}

pub(crate) fn revision_one(auth: &[u8; 32]) -> VerificationEmoji {
    let word = u32::from_be_bytes([auth[0], auth[1], auth[2], auth[3]]);
    VerificationEmoji(REVISION_ONE[word as usize % REVISION_ONE.len()])
}

