#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn matches_independent_dataview_and_set_vectors() {
        for (word, emoji) in [
            (0u32, "😅"),
            (1, "🤣"),
            (255, "💼"),
            (256, "📋"),
            (65535, "🎻"),
            (0x80000000, "🌋"),
            (u32::MAX, "😘"),
        ] {
            let mut auth = [0; 32];
            auth[..4].copy_from_slice(&word.to_be_bytes());
            let actual = revision_one(&auth);
            assert_eq!(actual.as_str(), emoji);
            assert_eq!(format!("{actual:?}"), "VerificationEmoji { redacted }");
            auth[4..].fill(255);
            assert_eq!(revision_one(&auth).as_str(), emoji);
        }
    }

    #[test]
    fn revision_one_has_unique_symbols_and_preserves_joined_codepoints() {
        assert_eq!(
            REVISION_ONE
                .iter()
                .collect::<std::collections::HashSet<_>>()
                .len(),
            308
        );
        assert_eq!(REVISION_ONE[294], "🍋\u{200d}🟩");
        assert_eq!(REVISION_ONE[295], "🐦\u{200d}🔥");
        assert!(!REVISION_ONE.contains(&"😁"));
        assert!(!REVISION_ONE.contains(&"💻"));
    }
}
